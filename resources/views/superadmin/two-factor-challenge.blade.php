    <script>
        let isRecovery = false;
        function toggleAuthMode() {
            isRecovery = !isRecovery;
            const totp = document.getElementById('totp-container');
            const recovery = document.getElementById('recovery-container');
            const btn = document.getElementById('toggle-recovery-btn');
            const codeInput = document.getElementById('code');
            const recoveryInput = document.getElementById('recovery_code');

            if (isRecovery) {
                totp.classList.add('hidden');
                recovery.classList.remove('hidden');
                codeInput.value = '';
                recoveryInput.focus();
                btn.textContent = 'Use authenticator code instead';
            } else {
                totp.classList.remove('hidden');
                recovery.classList.add('hidden');
                recoveryInput.value = '';
                codeInput.focus();
                btn.textContent = 'Use an emergency recovery code instead';
            }
        }
    </script>
